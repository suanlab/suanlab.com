'use client';

import { useState } from 'react';
import { isingDecimationGuide } from '@/data/ising-decimation-reader';
import { useLanguage } from '@/components/language-provider';
import { calculateFourSpinMarginal, calculateIsingDecimation } from '@/lib/learning-ising-decimation';
import { WavePlot } from './waves-plot';

const controls = 'grid min-w-0 grid-cols-1 gap-4';
const format = (value: number) => Number(value.toPrecision(6)).toString();

export default function IsingDecimationLab() {
  const { language } = useLanguage();
  const ko = language === 'ko';
  const [coupling, setCoupling] = useState(.4);
  const [size, setSize] = useState<8 | 16 | 32>(16);
  const steps = calculateIsingDecimation(coupling, size);
  const star = calculateFourSpinMarginal(coupling);
  return <section id="experiment" aria-labelledby="decimation-experiment-title" className={controls}>
    <h2 id="decimation-experiment-title">{ko ? '스핀을 제거해 유효 결합 구하기' : 'Remove spins and recover the effective coupling'}</h2>
    <label>{ko ? '초기 결합' : 'Initial coupling'} K = {coupling.toFixed(2)}
      <input className="block w-full" type="range" min={0} max={4} step={.01} value={coupling} aria-valuetext={coupling.toFixed(2)}
        onChange={e => setCoupling(Number(e.target.value))}/>
    </label>
    <label>{ko ? '고리의 초기 스핀 수' : 'Initial spins on the ring'}
      <select className="ml-2 rounded border border-border bg-background p-1" value={size}
        onChange={e => setSize(e.target.value === '8' ? 8 : e.target.value === '32' ? 32 : 16)}>
        {[8, 16, 32].map(n => <option key={n}>{n}</option>)}
      </select>
    </label>
    <WavePlot marker="ising-decimation" title={ko ? '단계마다 바뀌는 결합' : 'Coupling after each step'}
      xLabel={ko ? '제거 단계' : 'Decimation step'} yLabel="K"
      series={[{ color: 'blue', name: 'K', segments: [steps.map((step, i) => [i, step.coupling])] }]}
      dots={steps.map((step, i) => ({ color: 'blue', point: [i, step.coupling] }))}
      caption={ko ? '각 단계에서 스핀 수는 절반으로 줄고 격자 간격은 두 배가 됩니다.' : 'Each step halves the spin count and doubles the lattice spacing.'}/>
    <div className="overflow-x-auto" tabIndex={0} role="region" aria-label={ko ? '단계별 보존량' : 'Preserved quantities by step'}>
      <table className="w-full tabular-nums">
        <thead><tr>
          <th scope="col">N</th><th scope="col">a</th><th scope="col">K</th>
          <th scope="col">{ko ? '상관 길이 aξ' : 'Correlation length aξ'}</th>
          <th scope="col">{ko ? '복원된 log Z' : 'Recovered log Z'}</th>
        </tr></thead>
        <tbody>{steps.map(step => <tr key={step.sites}>
          <th scope="row">{step.sites}</th><td>{step.spacing}</td><td>{format(step.coupling)}</td>
          <td>{format(step.physicalCorrelationLength)}</td><td>{format(step.reconstructedLogPartition)}</td>
        </tr>)}</tbody>
      </table>
    </div>
    <h3>{ko ? '이웃이 네 개일 때 생기는 항' : 'An interaction generated by four neighbors'}</h3>
    <dl>
      <div><dt>{ko ? '네 스핀 계수' : 'Four-spin coefficient'} c₄</dt><dd>{format(star.fourSpin)}</dd></div>
      <div><dt>{ko ? '네 스핀 항을 버렸을 때 총변동 거리' : 'Total variation after dropping the four-spin term'}</dt><dd>{format(star.totalVariation)}</dd></div>
    </dl>
    <details>
      <summary>{ko ? '16개 배치의 확률 비교' : 'Compare probabilities for all 16 configurations'}</summary>
      <div className="overflow-x-auto" tabIndex={0} role="region" aria-label={ko ? '확률표' : 'Probability table'}>
        <table className="w-full tabular-nums">
          <thead><tr>
            <th scope="col">{ko ? '이웃 스핀' : 'Neighbor spins'}</th>
            <th scope="col">{ko ? '정확한 주변분포' : 'Exact marginal'}</th>
            <th scope="col">{ko ? '두 스핀 항만 사용' : 'Pair terms only'}</th>
          </tr></thead>
          <tbody>{star.distribution.map(row => <tr key={row.spins.join(',')}>
            <th scope="row">{row.spins.map(spin => spin === 1 ? '+' : '−').join(' ')}</th>
            <td>{format(row.exact)}</td><td>{format(row.truncated)}</td>
          </tr>)}</tbody>
        </table>
      </div>
    </details>
    {isingDecimationGuide.experiments.map(experiment => <details key={experiment.title.en}>
      <summary>{experiment.title[language]}</summary>
      <p>{experiment.predict[language]}</p><p>{experiment.action[language]}</p><p>{experiment.explain[language]}</p>
    </details>)}
  </section>;
}

export function IsingDecimationConcept({ language }: { language: 'ko' | 'en' }) {
  const ko = language === 'ko';
  const [summed, setSummed] = useState(false);
  return <section className="ai-intuition" id="visual-intuition" aria-labelledby="decimation-concept-title">
    <h2 id="decimation-concept-title">{ko ? '두 결합에서 한 유효 결합으로' : 'From two bonds to one effective bond'}</h2>
    <p>{isingDecimationGuide.intuition[language]}</p>
    <label className="my-4 flex items-center gap-2">
      <input type="checkbox" checked={summed} onChange={e => setSummed(e.target.checked)}/>
      {ko ? '가운데 스핀 합하기' : 'Sum the middle spin'}
    </label>
    <p className="ai-concept-equation" aria-live="polite">{summed ? 's ── K′ ── t' : 's ─ K ─ u ─ K ─ t'}</p>
    <p>{isingDecimationGuide.steps[0].explanation[language]}</p>
    <a href="#experiment">{ko ? '단계별 계산 보기' : 'Inspect the calculation by step'}</a>
  </section>;
}
