import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { learningUnits } from '../../src/data/interactive-book';
async function main() {
 const base='docs/online-learning/physics-math-for-ai/curriculum/';
 const [ko,en,coverage]=await Promise.all(['knowledge-map.json','knowledge-map.en.json','implementation-coverage.json'].map(async name=>JSON.parse(await fs.readFile(base+name,'utf8'))));
 assert.equal(coverage.implementedUnitCount,learningUnits.length);
 assert.deepEqual(ko.domains.map((d:{id:string})=>d.id),en.domains.map((d:{id:string})=>d.id));
 const unitIds=new Set(learningUnits.map(u=>u.id as string)),domainIds=new Set(ko.domains.map((d:{id:string})=>d.id));
 const domains=ko.domains.map((d:{id:string;title:string;topics:string[];prerequisites:string[]},i:number)=>{
  const translated=en.domains[i];assert.equal(d.topics.length,translated.topics.length,d.id);
  assert.ok(!/[가-힣]/.test(JSON.stringify(translated)),`Untranslated English: ${d.id}`);
  const entry=coverage.domains.find((x:{id:string})=>x.id===d.id);assert.ok(entry,d.id);
  for(const id of entry.implementedUnitIds)assert.ok(unitIds.has(id),id);
  for(const id of d.prerequisites)assert.ok(domainIds.has(id),id);
  return {id:d.id,title:{ko:d.title,en:translated.title},prerequisiteIds:d.prerequisites,topics:d.topics.map((title,j)=>({ko:title,en:translated.topics[j]})),unitIds:entry.implementedUnitIds};
 });
 const source=`// Generated by npm run learning:curriculum from the bilingual scope and coverage ledger.\nimport type { BookText, LearningUnitId } from './interactive-book';\nexport interface CurriculumDomain { id:string;title:BookText;prerequisiteIds:string[];topics:BookText[];unitIds:LearningUnitId[]; }\nexport const curriculumDomains:CurriculumDomain[] = ${JSON.stringify(domains,null,2)};\nexport const curriculumTopicCount=curriculumDomains.reduce((sum,domain)=>sum+domain.topics.length,0);\n`;
 await fs.writeFile('src/data/learning-curriculum.ts',source);
 console.log(`Curriculum synchronized: ${domains.length} domains, ${domains.reduce((n:number,d:{topics:unknown[]})=>n+d.topics.length,0)} bilingual topics, ${learningUnits.length} linked units.`);
}
main().catch(error=>{console.error(error);process.exitCode=1;});
