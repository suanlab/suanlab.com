/* Real worker/hook checks on an isolated esbuild harness, not integrated readers. */
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const result = { scope: 'isolated real worker and React hooks only; no integrated reader verification', errors: [], checks: [] };
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext(), page = await context.newPage();
  page.on('pageerror', e => result.errors.push(e.message));
  await page.goto('http://127.0.0.1:4186/');
  await page.waitForFunction(() => !!window.boltzmannGibbsProbe);
  const presets = await page.evaluate(() => window.boltzmannGibbsProbe.presets);
  const setInput = async input => page.evaluate(input => window.boltzmannGibbsProbe.setInput(input), input);
  const state = () => page.locator('#state').getAttribute('data-status');
  const ready = () => page.waitForFunction(() => document.querySelector('#state')?.getAttribute('data-status') === 'ready', {}, { timeout: 90000 });
  for (const preset of presets) { await setInput(preset.input); await ready(); }
  result.checks.push('all 27 prepared presets calculated by the separately bundled actual worker');
  const weighted = presets[0].input, gaussian = presets.find(p => p.id === 'gaussian-correlated').input, gibbs = presets.find(p => p.id === 'gibbs-ferromagnetic').input;
  const sampled = { ...gibbs, path: { seed: 1, bits: 32, steps: 2048, mode: 'systematic' } };
  await setInput(sampled); await ready(); result.checks.push('real worker returns the maximum-length finite-bit path');
  const heavy = { ...gibbs, parameters: { ...gibbs.parameters, couplingEnergy: Number.MIN_VALUE, firstFieldEnergy: 800 * 1.380649e-23 * Number.MAX_VALUE,
    secondFieldEnergy: 800 * 1.380649e-23 * Number.MAX_VALUE, temperature: Number.MAX_VALUE, observationSteps: [64] } };
  let acknowledged = await page.evaluate(() => window.boltzmannGibbsProbe.metrics.acknowledged);
  await setInput(heavy);
  await page.waitForFunction(n => window.boltzmannGibbsProbe.metrics.acknowledged > n, acknowledged);
  const ticks = await page.evaluate(() => window.boltzmannGibbsProbe.metrics.ticks);
  await page.waitForTimeout(120);
  assert.ok(await page.evaluate(n => window.boltzmannGibbsProbe.metrics.ticks > n + 2, ticks));
  await setInput(gaussian); await ready();
  result.checks.push('heavy scientific calculation leaves the main event loop responsive; replacement never exposes a stale result');
  acknowledged = await page.evaluate(() => window.boltzmannGibbsProbe.metrics.acknowledged);
  await setInput(heavy); await page.waitForFunction(n => window.boltzmannGibbsProbe.metrics.acknowledged > n, acknowledged);
  await page.locator('#cancel').click(); await page.waitForFunction(() => document.querySelector('#state')?.getAttribute('data-status') === 'idle');
  await page.waitForFunction(() => window.boltzmannGibbsProbe.metrics.live === 0);
  await page.locator('#retry').click(); await ready(); result.checks.push('cancel and explicit retry clean up and restart the real worker');
  const before = await page.evaluate(() => window.boltzmannGibbsProbe.metrics.started);
  await page.evaluate(() => window.boltzmannGibbsProbe.settings('ko', 'dark'));
  await ready(); assert.equal(await page.evaluate(() => window.boltzmannGibbsProbe.metrics.started), before);
  result.checks.push('language/theme-only renders preserve the matching computation');
  await page.evaluate(() => window.boltzmannGibbsProbe.metrics.blocked = true); await setInput(weighted);
  await page.waitForFunction(() => document.querySelector('#state')?.getAttribute('data-status') === 'error');
  assert.equal(await page.locator('#error').textContent(), 'unavailable');
  assert.equal(await page.locator('#state').getAttribute('data-ready-key'), '');
  await page.evaluate(() => window.boltzmannGibbsProbe.metrics.blocked = false); await page.locator('#retry').click(); await ready();
  result.checks.push('worker construction failure exposes no old result and recovers by retry');
  await context.route('**/worker.js', route => route.abort()); await setInput(gaussian);
  await page.waitForFunction(() => document.querySelector('#state')?.getAttribute('data-status') === 'error');
  await context.unroute('**/worker.js'); await page.locator('#retry').click(); await ready(); result.checks.push('actual worker-load failure and recovery');
  await setInput({ ...weighted, parameters: { ...weighted.parameters, temperature: null } });
  await page.waitForFunction(() => document.querySelector('#state')?.getAttribute('data-status') === 'error');
  assert.equal(await page.locator('#error').textContent(), 'invalid-input'); await setInput(null);
  const beforeInvalidSeries = await page.evaluate(() => window.boltzmannGibbsProbe.metrics.started);
  await page.evaluate(() => window.boltzmannGibbsProbe.setSeries([null]));
  await page.waitForFunction(() => document.querySelector('#series')?.getAttribute('data-status') === 'error');
  assert.equal(await page.evaluate(() => window.boltzmannGibbsProbe.metrics.started), beforeInvalidSeries);
  await page.evaluate(input => window.boltzmannGibbsProbe.setSeries([input]), weighted);
  await page.waitForFunction(() => document.querySelector('#series')?.getAttribute('data-status') === 'ready');
  result.checks.push('malformed series inputs fail before worker creation and recover with new valid inputs');
  await page.evaluate(inputs => window.boltzmannGibbsProbe.setSeries(inputs), [weighted, heavy, gibbs]);
  await page.waitForFunction(() => window.boltzmannGibbsProbe.metrics.live > 0);
  await page.evaluate(input => window.boltzmannGibbsProbe.setSeries([input]), gaussian);
  await page.waitForFunction(() => document.querySelector('#series')?.getAttribute('data-status') === 'ready' && document.querySelector('#series')?.getAttribute('data-count') === '1');
  result.checks.push('fixed-series replacement hides partial and previous responses');
  await page.evaluate(() => window.boltzmannGibbsProbe.setSeries([]));
  await setInput(heavy); await page.waitForFunction(() => window.boltzmannGibbsProbe.metrics.live > 0);
  await page.evaluate(() => window.boltzmannGibbsProbe.unmount()); await page.waitForFunction(() => window.boltzmannGibbsProbe.metrics.live === 0);
  await page.evaluate(() => { window.boltzmannGibbsProbe.setInput(null); window.boltzmannGibbsProbe.mount(); });
  await setInput(weighted); await ready();
  await page.evaluate(() => { window.boltzmannGibbsProbe.setInput(null); window.boltzmannGibbsProbe.setSeries([]); });
  await page.waitForFunction(() => window.boltzmannGibbsProbe.metrics.live === 0);
  const metrics = await page.evaluate(() => window.boltzmannGibbsProbe.metrics);
  assert.equal(metrics.wrongReadyInputs, 0); assert.equal(metrics.wrongSeriesInputs, 0); assert.equal(metrics.live, 0); assert.equal(metrics.started, metrics.terminated);
  result.checks.push('unmount/remount terminates all workers, with no stale calculation or series frames');
  result.metrics = { ...metrics, history: undefined }; assert.equal(await state(), 'idle'); assert.deepEqual(result.errors, []);
  await context.close();
} finally { await browser.close(); await fs.writeFile('.runtime/learning/boltzmann-gibbs-worker/browser-result.json', JSON.stringify(result, null, 2)+'\n'); }
console.log(JSON.stringify(result, null, 2));
